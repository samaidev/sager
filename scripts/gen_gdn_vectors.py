#!/usr/bin/env python3
# gen_gdn_vectors.py - generate golden test vectors for the SAGER GDN
# (gated delta net) CPU reference, straight from the spec conventions
# documented in docs/gdn-kernel.md:
#
#   C-GDN-1  q,k: per-head L2-normalize (y = x / sqrt(sum(x^2) + eps)),
#            NO learnable weight (real Sage-A1.5 GDN layers)
#   C-GDN-2  beta = sigmoid(b), per v-head
#   C-GDN-3  g = A[h] * softplus(a + dt_bias[h]) per v-head, where the
#            checkpoint stores A = -exp(A_log) pre-negated; alpha = exp(g)
#   C-GDN-4  state S [ratio*V x K]; step:
#              u     = S @ k
#              S_new = alpha*S - alpha*beta*u*k^T + beta*v*k^T   (rank-1 delta)
#              y     = S_new @ q                                 (inclusive)
#   C-GDN-5  conv: y_d = silu(sum_j w[d,j]*win_d[j] + b_d); window = state(ck-1) + x
#   C-GDN-6  out norm: o = rmsnorm(y, w_on) * silu(z)   (per v-head)
#
# Outputs tests/gdn_vectors.hpp with decimal constants (float) so the C++
# test can compare with atol 1e-4 (fp32 math both sides).
import numpy as np

rng = np.random.default_rng(20261124)

# small but non-trivial geometry (ratio 2, like Sage-A1.5's 16k/32v)
NK, NV, K, V, CK = 2, 4, 4, 6, 4
RATIO = NV // NK
CONV_DIM = 2 * NK * K + NV * V          # 16 + 24 = 40
PROJ_ROWS = CONV_DIM + NV * V           # + z = 64

def rmsnorm(x, w, eps=1e-6):
    return x / np.sqrt(np.mean(x * x) + eps) * w

def l2n(x):
    return x / np.linalg.norm(x)

def silu(x):
    return x / (1.0 + np.exp(-x))

def softplus(x):
    return np.log1p(np.exp(-np.abs(x))) + np.maximum(x, 0.0)

def delta_step_row(S, j, qh, kh, vj, alpha_j, beta_j, K):
    """One state-row delta update (spec C-GDN-4, per-row alpha/beta).
    Returns (S_new, y_j). Other rows are untouched this call - the caller
    walks rows in order; u is recomputed against the CURRENT S row."""
    u = S[j] @ kh
    S_new = S.copy()
    S_new[j] = alpha_j * S[j] - alpha_j * beta_j * u * kh \
               + beta_j * vj * kh
    y_j = S_new[j] @ qh
    return S_new, y_j

# ---------------- case 1: conv step ----------------
conv_state = rng.standard_normal((CONV_DIM, CK - 1)).astype(np.float64)
conv_w = rng.standard_normal((CONV_DIM, CK)).astype(np.float64)
conv_b = rng.standard_normal(CONV_DIM).astype(np.float64)
xrow = rng.standard_normal(CONV_DIM).astype(np.float64)
win = np.concatenate([conv_state, xrow[:, None]], axis=1)   # [D, CK]
conv_out = silu((win * conv_w).sum(axis=1) + conv_b)
conv_state_new = np.concatenate([conv_state[:, 1:], xrow[:, None]], axis=1)

# ---------------- case 2: gate (per V-head) ----------------
b_raw = rng.standard_normal(NV).astype(np.float64)
a_raw = rng.standard_normal(NV).astype(np.float64)
A = -np.exp(rng.standard_normal(NV).astype(np.float64) * 0.3)  # pre-negated
dt_bias = rng.standard_normal(NV).astype(np.float64) * 0.3
beta = 1.0 / (1.0 + np.exp(-b_raw))
dt = softplus(a_raw + dt_bias)
g = A * dt
alpha = np.exp(g)

# ---------------- case 3: delta step ----------------
S0 = rng.standard_normal((NK, RATIO * V, K)).astype(np.float64)
# C-GDN-1: plain L2, no weights. eps matches the engine (norm_eps).
GEPS = 1e-6
q_raw = rng.standard_normal((NK, K)).astype(np.float64)
k_raw = rng.standard_normal((NK, K)).astype(np.float64)
v_all = rng.standard_normal((NV, V)).astype(np.float64)   # [nv, V] heads

qh = np.stack([q_raw[h] / np.sqrt((q_raw[h] ** 2).sum() + GEPS)
               for h in range(NK)])
kh = np.stack([k_raw[h] / np.sqrt((k_raw[h] ** 2).sum() + GEPS)
               for h in range(NK)])
S1 = np.empty_like(S0)
y_all = np.empty((NK, RATIO * V))
for h in range(NK):
    # alpha/beta are per V-head: row j of k-head h is v-head h*ratio + j/V.
    vh_vec = v_all[h * RATIO:(h + 1) * RATIO].reshape(RATIO * V)
    S_h = S0[h].copy()
    y_h = np.empty(RATIO * V)
    for j in range(RATIO * V):
        vhead = h * RATIO + j // V
        S_h, y_h[j] = delta_step_row(S_h, j, qh[h], kh[h], vh_vec[j],
                                     alpha[vhead], beta[vhead], K)
    S1[h], y_all[h] = S_h, y_h

# ---------------- case 4: out norm ----------------
won = np.abs(rng.standard_normal(V)) + 0.5
z_all = rng.standard_normal((NV, V)).astype(np.float64)
o_all = np.empty((NV, V))
for w in range(NV):
    h, j = divmod(w, RATIO)
    o_all[w] = rmsnorm(y_all[h].reshape(RATIO, V)[j], won) * silu(z_all[w])

def fmt(a):
    return ", ".join(f"{float(x):.9e}f" for x in np.asarray(a).reshape(-1))

lines = []
lines.append("// gdn_vectors.hpp - golden test vectors generated by")
lines.append("// scripts/gen_gdn_vectors.py (numpy reference of docs/gdn-kernel.md).")
lines.append("// DO NOT EDIT BY HAND - regenerate instead.")
lines.append("#pragma once")
lines.append("#include <cstddef>")
lines.append("namespace sager::test {")
lines.append("struct GdnVec { int nk, nv, K, V, ck; };")

def emit(name, arr):
    lines.append(f"inline const float {name}[] = {{{fmt(arr)}}};")
    lines.append(f"inline const size_t {name}_n = sizeof({name}) / sizeof(float);")

lines.append(f"inline constexpr GdnVec kGdnVec = {{{NK}, {NV}, {K}, {V}, {CK}}};")
emit("g_conv_state", conv_state)
emit("g_conv_w", conv_w)
emit("g_conv_b", conv_b)
emit("g_conv_x", xrow)
emit("g_conv_out", conv_out)
emit("g_conv_state_new", conv_state_new)
emit("g_b_raw", b_raw)
emit("g_a_raw", a_raw)
emit("g_A", A)
emit("g_dt_bias", dt_bias)
emit("g_alpha", alpha)
emit("g_beta", beta)
emit("g_S0", S0)
emit("g_q_raw", q_raw)
emit("g_k_raw", k_raw)
emit("g_v_all", v_all)
emit("g_qh", qh)
emit("g_kh", kh)
emit("g_S1", S1)
emit("g_y", y_all)
emit("g_won", won)
emit("g_z", z_all)
emit("g_o", o_all)
lines.append("}  // namespace sager::test")
lines.append("")

import os
os.makedirs("tests", exist_ok=True)
with open("tests/gdn_vectors.hpp", "w") as f:
    f.write("\n".join(lines))
print("wrote tests/gdn_vectors.hpp",
      sum(l.count(",") for l in lines), "floats")
